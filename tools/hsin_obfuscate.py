#!/usr/bin/env python3
"""
HSIN release obfuscator.

Run ONLY against the RELEASE staging directory (never the dev build, never
the source tree) - build_release.sh's build_release() calls this right
after staging, before integrity hashing.

What it does, in order:
  1. Renames every file under core/, engine/, extreme/, config/, capability/
     (minus a short excluded list) to a random hex name, same directory,
     same extension.
  2. Adds one small plain-text helper file (core/<random>.sh) containing a
     `_hsin_ld()` function: base64-decode + gunzip + eval into the CURRENT
     shell. This is what makes obfuscated files behave like the plain
     files they replaced when dot-sourced.
  3. Rewrites every text file in the whole staged tree: any reference to
     an old relative path - however it's quoted/escaped/prefixed
     ($HSIN_MODULE_PATH/x, $MODPATH/x, ${MODPATH:-default}/x, a bare path
     in a list, inside an already-escaped sh -c string, inside a heredoc -
     gets repointed at the new name, and every `. "<path>"`-style
     dot-source of a file that's about to be content-encoded becomes
     `. "<path-to-helper>"; _hsin_ld "<new-path>"` so it still works from
     a freshly spawned shell (setsid/nohup/heredoc), not just the
     process that originally sourced it.
  4. For every renamed *.sh file under core/engine/extreme: strips
     comment-only/blank lines, then gzip+base64 encodes the body in place.
     Everything else eligible (*.conf/*.json) is renamed only - it's data
     read with a while-read loop or grep, not sourced as shell, so
     encoding it would need touching every read call-site for little gain.
  5. Writes a TSV rename map (old_relpath<TAB>new_relpath) to argv[2] so
     build_release.sh can translate its own PROTECTED_FILES_* lists
     before hashing.

This is obfuscation, not encryption - anyone willing to decode a base64
blob by hand can still read it. The point is raising the bar against
casual copy-paste/skim-reading, not defeating a determined reverse
engineer.
"""
import sys
import re
import gzip
import base64
import random
import pathlib

def die(msg):
    print(f"[hsin_obfuscate] ERROR: {msg}", file=sys.stderr)
    sys.exit(1)

if len(sys.argv) != 3:
    die("usage: hsin_obfuscate.py <stage_dir> <map_output_file>")

STAGE = pathlib.Path(sys.argv[1]).resolve()
MAP_OUT = pathlib.Path(sys.argv[2])

if not STAGE.is_dir():
    die(f"stage dir not found: {STAGE}")

# ---------------------------------------------------------------------------
# Scope
# ---------------------------------------------------------------------------

RENAME_ROOTS = ["core", "engine", "extreme", "config", "capability"]

# Content-encode (gzip+base64) is restricted to engine/ and extreme/ only.
# core/*.sh is what action.sh sources on EVERY WebUI click (status polling
# every ~3s) and what service.sh/post-fs-data.sh source at boot - keeping
# it as plain (but still randomly-named) text means the highest-traffic,
# highest-blast-radius-if-broken code path never depends on the
# decode/eval chain at all. engine/*.sh (the actual per-domain tweaks) and
# extreme/*.sh are touched far less often (profile apply, background
# guard loop) and are more isolated, so they're where encoding actually
# buys obfuscation without risking the interactive UI path.
ENCODE_ROOTS = {"engine", "extreme"}

# Never renamed even though it lives under an eligible root: copied out to
# the user's own editable /sdcard config by customize.sh/service.sh, kept
# human-readable on purpose.
RENAME_EXCLUDE = {"config/hsin.conf"}

ENCODE_EXTS = {".sh"}
BINARY_EXTS = {".png", ".jpg", ".jpeg", ".webp", ".gif", ".ttf", ".otf", ".zip"}

HELPER_VIRTUAL_OLD = "core/_hsin_loader.sh"
HELPER_CONTENT = (
    "#!/system/bin/sh\n"
    "# HSIN loader - decode+run an obfuscated module file in the CURRENT\n"
    "# shell (same effect as `. \"$1\"` on the original plain-text file).\n"
    "# Auto-generated by hsin_obfuscate.py at release build time.\n"
    "_hsin_ld() {\n"
    "    eval \"$(base64 -d \"$1\" 2>/dev/null | gzip -dc 2>/dev/null)\"\n"
    "}\n"
)

# Entry points that stay plain (never renamed, never encoded) but still
# get their comment lines stripped for release - these are the files a
# curious person opens first, and they're exactly where the long
# "why this exists" comments (like action.sh's ALLOW_EXTREME explanation)
# live. Shebang line is always kept for these since a couple of them
# (bin/hsin, bin/hsin-cli) can be invoked directly by execve, which needs
# it to pick the interpreter.
PLAIN_ENTRY_POINTS = {
    "action.sh", "service.sh", "post-fs-data.sh",
    "customize.sh", "uninstall.sh", "bin/hsin", "bin/hsin-cli",
}

COMMENT_ONLY_RE = re.compile(r"^\s*#")

def strip_comments(text: str, keep_shebang: bool) -> str:
    lines = text.split("\n")
    out = []
    for i, line in enumerate(lines):
        if i == 0 and keep_shebang and line.startswith("#!"):
            out.append(line)
            continue
        if line.startswith("#!"):
            continue
        stripped = line.strip()
        if stripped == "" or COMMENT_ONLY_RE.match(stripped):
            continue
        out.append(line.rstrip())
    return "\n".join(out) + "\n"

def minify_sh(text: str) -> str:
    return strip_comments(text, keep_shebang=False)

random.seed()
_used_names = set()

def random_name(ext):
    while True:
        cand = "".join(random.choice("0123456789abcdef") for _ in range(12)) + ext
        if cand not in _used_names:
            _used_names.add(cand)
            return cand

def is_probably_text(path: pathlib.Path):
    if path.suffix.lower() in BINARY_EXTS:
        return False
    try:
        with open(path, "rb") as f:
            chunk = f.read(8192)
        chunk.decode("utf-8")
        return True
    except Exception:
        return False

# ---------------------------------------------------------------------------
# Step 1: collect eligible files, assign new random names
# ---------------------------------------------------------------------------

rename_map = {}  # old_rel (posix) -> new_rel (posix)

for root in RENAME_ROOTS:
    root_path = STAGE / root
    if not root_path.is_dir():
        continue
    for p in sorted(root_path.rglob("*")):
        if not p.is_file():
            continue
        rel = p.relative_to(STAGE).as_posix()
        if rel in RENAME_EXCLUDE:
            continue
        new_base = random_name(p.suffix)
        new_rel = (p.parent.relative_to(STAGE) / new_base).as_posix()
        rename_map[rel] = new_rel

if not rename_map:
    print("[hsin_obfuscate] nothing eligible found, skipping")
    sys.exit(0)

# Helper file: create it now with a random name of its own, register it in
# the map under a virtual old-name so build_release.sh can find/protect it.
helper_new_rel = "core/" + random_name(".sh")
rename_map[HELPER_VIRTUAL_OLD] = helper_new_rel

# ---------------------------------------------------------------------------
# Step 2: rewrite every text file in the stage for path references, while
# old paths still exist on disk (nothing physically moved yet).
# ---------------------------------------------------------------------------

all_files = [p for p in STAGE.rglob("*") if p.is_file()]

# Matches:  . "$VAR/rel.sh"   . \"$VAR/rel.sh\"   . "\$VAR/rel.sh"
#           . '${VAR:-default}/rel.sh'   (and mixes of the above)
DOTSRC_RE = re.compile(
    r'(?P<indent>[ \t]*)\.\s+'
    r'(?P<oqb>\\)?(?P<qc>[\'"])'
    r'(?P<db>\\)?(?P<prefix>\$\{[A-Za-z_]+(?::-[^}]*)?\}|\$[A-Za-z_]+)'
    r'/(?P<rel>[A-Za-z0-9_./-]+\.sh)'
    r'(?P<cqb>\\)?(?P=qc)',
    re.MULTILINE,
)

texts = {}
for p in all_files:
    if p == MAP_OUT or not is_probably_text(p):
        continue
    try:
        texts[p] = p.read_text(encoding="utf-8")
    except Exception:
        continue

ordered_old = sorted(
    (k for k in rename_map if k != HELPER_VIRTUAL_OLD), key=len, reverse=True
)

for p, content in list(texts.items()):
    original = content

    def _swap_dotsource(m):
        rel = m.group("rel")
        if rel not in rename_map:
            return m.group(0)
        indent = m.group("indent")
        oqb = m.group("oqb") or ""
        qc = m.group("qc")
        db = m.group("db") or ""
        prefix = m.group("prefix")
        new_rel = rename_map[rel]
        target_ref = f'{oqb}{qc}{db}{prefix}/{new_rel}{oqb}{qc}'
        _root = rel.split("/", 1)[0]
        if _root not in ENCODE_ROOTS:
            # Renamed but NOT content-encoded (core/*.sh) - still plain
            # shell, so a normal dot-source with the new name is enough.
            return f'{indent}. {target_ref}'
        helper_ref = f'{oqb}{qc}{db}{prefix}/{helper_new_rel}{oqb}{qc}'
        return f'{indent}. {helper_ref}; _hsin_ld {target_ref}'

    content = DOTSRC_RE.sub(_swap_dotsource, content)

    # Bare relpath substitution for everything else: lists like
    # core/protect.sh's _critical_files, or any reference this pass's
    # dot-source regex didn't need to touch.
    for old_rel in ordered_old:
        new_rel = rename_map[old_rel]
        if old_rel != new_rel and old_rel in content:
            content = content.replace(old_rel, new_rel)

    if content != original:
        texts[p] = content

for p, content in texts.items():
    rel = p.relative_to(STAGE).as_posix()
    if rel in PLAIN_ENTRY_POINTS:
        content = strip_comments(content, keep_shebang=True)
    p.write_text(content, encoding="utf-8")

# ---------------------------------------------------------------------------
# Step 3: physically rename + encode
# ---------------------------------------------------------------------------


def encode_blob(text: str) -> bytes:
    comp = gzip.compress(text.encode("utf-8"), compresslevel=9)
    return base64.encodebytes(comp)

n_encoded = 0
for old_rel, new_rel in rename_map.items():
    if old_rel == HELPER_VIRTUAL_OLD:
        continue
    old_path = STAGE / old_rel
    new_path = STAGE / new_rel
    if not old_path.exists():
        print(f"[hsin_obfuscate] WARNING: {old_rel} listed but missing, skipping", file=sys.stderr)
        continue
    data = old_path.read_bytes()
    _root = old_rel.split("/", 1)[0]
    _suffix = pathlib.PurePosixPath(old_rel).suffix
    if _root in ENCODE_ROOTS and _suffix in ENCODE_EXTS:
        try:
            text = data.decode("utf-8")
            data = encode_blob(minify_sh(text))
            n_encoded += 1
        except UnicodeDecodeError:
            print(f"[hsin_obfuscate] WARNING: {old_rel} not valid utf-8, renamed without encoding", file=sys.stderr)
    elif _suffix in ENCODE_EXTS:
        # Renamed-only .sh (core/*) - still plain shell, but strip the
        # comment lines same as the encoded ones so a skim-read doesn't
        # give away as much. Shebang kept: harmless here since these are
        # only ever dot-sourced, never exec'd, but keeping it costs nothing.
        try:
            data = strip_comments(data.decode("utf-8"), keep_shebang=True).encode("utf-8")
        except UnicodeDecodeError:
            pass
    old_path.unlink()
    new_path.parent.mkdir(parents=True, exist_ok=True)
    new_path.write_bytes(data)

helper_path = STAGE / helper_new_rel
helper_path.parent.mkdir(parents=True, exist_ok=True)
helper_path.write_text(HELPER_CONTENT, encoding="utf-8")

# Clean up now-empty directories left behind (cosmetic).
for root in RENAME_ROOTS:
    root_path = STAGE / root
    if not root_path.is_dir():
        continue
    for d in sorted(root_path.rglob("*"), key=lambda x: -len(str(x))):
        if d.is_dir():
            try:
                d.rmdir()
            except OSError:
                pass

# ---------------------------------------------------------------------------
# Step 4: emit the rename map (includes the helper's virtual entry) so
# build_release.sh can translate PROTECTED_FILES_LIGHT/EXTRA against it.
# ---------------------------------------------------------------------------

with open(MAP_OUT, "w", encoding="utf-8") as f:
    for old_rel, new_rel in rename_map.items():
        f.write(f"{old_rel}\t{new_rel}\n")

print(f"[hsin_obfuscate] renamed {len(rename_map)} files "
      f"(helper: {helper_new_rel}), encoded {n_encoded} scripts")
